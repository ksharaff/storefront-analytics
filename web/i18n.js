// Arabic counting forms for "… ago" (2026-09-29). Arabic changes the
// noun with the number: 1 = the noun alone, 2 = the dual, 3–10 = plural,
// 11 and up = singular again (with tanween for days).
function arHours(n) {
  if (n === 1) return "ساعة";
  if (n === 2) return "ساعتين";
  return n <= 10 ? `${n} ساعات` : `${n} ساعة`;
}
function arDays(n) {
  if (n === 1) return "يوم";
  if (n === 2) return "يومين";
  return n <= 10 ? `${n} أيام` : `${n} يومًا`;
}

